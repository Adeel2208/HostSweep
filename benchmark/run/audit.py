#!/usr/bin/env python3
"""Stage 9 self-audit: check the result files before anything is handed over.

Every check answers one question about whether the numbers are real:

  1. Row counts        do the files contain what the stages claim to have run?
  2. Provenance        does every row have a metrics JSON and a .time file?
  3. Replicate spacing are replicates measured, or generated from one value?
  4. Cross-file        do files that must agree actually agree?
  5. Carried-over      does any summary land exactly on a pre-existing
                       published figure?

Exits non-zero if any check fails, so it can gate the packaging step.

Usage:
    python benchmark/run/audit.py [--run-dir benchmark/run] [--out AUDIT.md]
"""
import argparse
import csv
import json
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

# Figures already published in README.md / the manuscript. A freshly computed
# mean landing exactly on one of these is a red flag: it means a value was
# carried over rather than measured.
PUBLISHED = {
    "sensitivity_pct": [99.84, 99.41, 96.24, 94.87, 91.45],
    "fpr_pct": [2.76, 2.91, 3.82, 5.23, 7.41],
    "runtime_min": [11.2, 13.6, 35.8, 28.4, 142.3],
    "peak_mem_gb": [6.8, 6.5, 11.2, 14.7, 8.9],
}

REPORT = []
FAILURES = []
WARNINGS = []


def emit(line=""):
    REPORT.append(line)
    print(line)


def fail(msg):
    FAILURES.append(msg)
    emit("  **FAIL** %s" % msg)


def warn(msg):
    WARNINGS.append(msg)
    emit("  **WARN** %s" % msg)


def ok(msg):
    emit("  OK   %s" % msg)


def read_csv(path):
    if not path.exists():
        return None
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def as_float(value):
    try:
        s = str(value).strip()
        return float(s) if s not in ("", "NA", "FAILED", "None") else None
    except (TypeError, ValueError):
        return None


# --- 1. Row counts ----------------------------------------------------
def check_row_counts(run_dir, files):
    emit("\n## 1. Row counts\n")
    expectations = {
        "per_library.csv": "6 tools x 12 synthetic libraries x 3 runs = 216 "
                           "(+ 30 real x 3 = 90 if the real arm ran)",
        "ablation.csv": "3 configs x 12 libraries x 3 runs = 108",
        "threshold_sweep.csv": "5 entropies x 5 lengths x 3 libraries = 75",
        "synthetic_manifest.csv": "12",
        "accessions_verified.csv": "30",
        "downstream.csv": "3 methods x (12 synthetic + 6 real) = 54",
        "kraken2_human.csv": "3 methods x 18 libraries = 54",
    }
    for name, expected in expectations.items():
        rows = files.get(name)
        if rows is None:
            emit("  --   %-26s ABSENT (expected %s)" % (name, expected))
        else:
            emit("  --   %-26s %d rows (expected %s)" % (name, len(rows), expected))
            if not rows:
                fail("%s exists but has no rows" % name)


# --- 2. Provenance ----------------------------------------------------
def check_provenance(run_dir, per_library):
    emit("\n## 2. Provenance: every row traceable to files on disk\n")
    if not per_library:
        emit("  --   per_library.csv absent or empty; nothing to trace")
        return

    results = run_dir / "results"
    missing_metrics, missing_time = [], []
    for row in per_library:
        lib, tool, run = row.get("library"), row.get("tool"), row.get("run")
        mj = results / lib / ("metrics_%s_run%s.json" % (tool, run))
        tf = results / lib / ("%s_run%s.time" % (tool, run))
        if not mj.exists():
            missing_metrics.append(str(mj.relative_to(run_dir)))
        if not tf.exists():
            missing_time.append(str(tf.relative_to(run_dir)))

    if missing_metrics:
        fail("%d/%d rows have no metrics JSON, e.g. %s"
             % (len(missing_metrics), len(per_library), missing_metrics[:3]))
    else:
        ok("all %d rows have a metrics JSON" % len(per_library))

    if missing_time:
        fail("%d/%d rows have no .time file, e.g. %s"
             % (len(missing_time), len(per_library), missing_time[:3]))
    else:
        ok("all %d rows have a .time file" % len(per_library))


# --- 3. Replicate spacing --------------------------------------------
def check_replicate_spacing(per_library, ablation):
    emit("\n## 3. Replicate spacing: measured or generated?\n")
    emit("Real replicates of a deterministic pipeline are *identical*; real "
         "replicates of a timed one are *irregularly scattered*. Gaps that "
         "repeat across many groups are the signature of values generated by "
         "perturbing a single measurement.\n")

    groups = defaultdict(list)
    for source, rows in (("per_library", per_library), ("ablation", ablation)):
        for row in rows or []:
            key_tool = row.get("tool") or row.get("config")
            for col in ("sensitivity_pct", "fpr_pct", "runtime_min", "peak_mem_gb"):
                v = as_float(row.get(col))
                if v is not None:
                    groups[(source, row.get("library"), key_tool, col)].append(v)

    if not groups:
        emit("  --   no replicate data to check")
        return

    gap_counts = defaultdict(int)
    identical = scattered = 0
    for key, values in groups.items():
        if len(values) < 2:
            continue
        values = sorted(values)
        gaps = tuple(round(b - a, 6) for a, b in zip(values, values[1:]))
        if all(g == 0 for g in gaps):
            identical += 1
        else:
            scattered += 1
            gap_counts[gaps] += 1

    emit("  %d groups identical across replicates (expected for deterministic steps)"
         % identical)
    emit("  %d groups vary across replicates" % scattered)

    if scattered:
        worst, count = max(gap_counts.items(), key=lambda kv: kv[1])
        share = count / scattered
        emit("  most common gap pattern %s appears in %d/%d varying groups (%.0f%%)"
             % (list(worst), count, scattered, 100 * share))
        # An identical non-zero gap pattern shared by many independent groups
        # cannot arise from independently timed runs.
        if count >= 3 and share > 0.30 and any(g != 0 for g in worst):
            fail("LOUD: %d independent groups share the exact gap pattern %s. "
                 "Independently measured replicates do not do this -- these "
                 "values look generated from a single measurement."
                 % (count, list(worst)))
        else:
            ok("no single non-zero gap pattern dominates")


# --- 4. Cross-file agreement -----------------------------------------
def check_cross_file(per_library, ablation, manifest):
    emit("\n## 4. Cross-file agreement\n")

    # dual_pass in ablation.csv should match hostsweep in per_library.csv.
    if per_library and ablation:
        hs = {}
        for row in per_library:
            if row.get("tool") == "hostsweep":
                hs[(row.get("library"), row.get("run"))] = as_float(row.get("sensitivity_pct"))
        mismatches = []
        compared = 0
        for row in ablation:
            if row.get("config") != "dual_pass":
                continue
            key = (row.get("library"), row.get("run"))
            if key not in hs or hs[key] is None:
                continue
            a = as_float(row.get("sensitivity_pct"))
            if a is None:
                continue
            compared += 1
            if abs(a - hs[key]) > 0.01:
                mismatches.append((key, a, hs[key]))
        if compared == 0:
            emit("  --   no overlapping (library, run) pairs to compare")
        elif mismatches:
            fail("dual_pass != hostsweep sensitivity in %d/%d comparisons, e.g. %s"
                 % (len(mismatches), compared, mismatches[:3]))
        else:
            ok("dual_pass matches hostsweep sensitivity in all %d comparisons" % compared)
    else:
        emit("  --   per_library.csv or ablation.csv absent; skipped")

    # host_pct must be the realised fraction from the manifest.
    if per_library and manifest:
        realised = {}
        for row in manifest:
            v = as_float(row.get("realised_fraction"))
            if v is not None:
                realised[row.get("library")] = v * 100 if v <= 1 else v
        bad, compared = [], 0
        for row in per_library:
            lib = row.get("library")
            hp = as_float(row.get("host_pct"))
            if lib not in realised or hp is None:
                continue
            compared += 1
            if abs(hp - realised[lib]) > 0.01:
                bad.append((lib, hp, realised[lib]))
        if compared == 0:
            emit("  --   no synthetic libraries to compare host_pct against")
        elif bad:
            fail("host_pct disagrees with synthetic_manifest.csv for %d rows, e.g. %s"
                 % (len(bad), bad[:3]))
        else:
            ok("host_pct matches the manifest's realised fraction in all %d rows" % compared)
    else:
        emit("  --   per_library.csv or synthetic_manifest.csv absent; skipped")


# --- 5. Carried-over values ------------------------------------------
def check_carried_over(per_library):
    emit("\n## 5. Carried-over values\n")
    if not per_library:
        emit("  --   per_library.csv absent; nothing to compare")
        return

    by_tool = defaultdict(lambda: defaultdict(list))
    for row in per_library:
        for col in PUBLISHED:
            v = as_float(row.get(col))
            if v is not None:
                by_tool[row.get("tool")][col].append(v)

    hits = 0
    for tool, cols in sorted(by_tool.items()):
        for col, values in sorted(cols.items()):
            mean = sum(values) / len(values)
            for pub in PUBLISHED[col]:
                if abs(mean - pub) < 0.005:
                    fail("%s %s mean = %.4f lands exactly on the published %.2f. "
                         "Investigate before reporting." % (tool, col, mean, pub))
                    hits += 1
    if hits == 0:
        ok("no computed mean coincides with a pre-existing published figure")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", default=str(Path(__file__).resolve().parent))
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    run_dir = Path(args.run_dir)
    out = Path(args.out) if args.out else run_dir / "AUDIT.md"

    emit("# Benchmark self-audit")
    emit()
    emit("Run directory: `%s`" % run_dir)
    emit()

    names = ["per_library.csv", "ablation.csv", "threshold_sweep.csv",
             "synthetic_manifest.csv", "accessions_verified.csv",
             "downstream.csv", "kraken2_human.csv", "labelling_sensitivity.csv"]
    files = {n: read_csv(run_dir / n) for n in names}

    check_row_counts(run_dir, files)
    check_provenance(run_dir, files["per_library.csv"])
    check_replicate_spacing(files["per_library.csv"], files["ablation.csv"])
    check_cross_file(files["per_library.csv"], files["ablation.csv"],
                     files["synthetic_manifest.csv"])
    check_carried_over(files["per_library.csv"])

    emit("\n## Verdict\n")
    present = [n for n in names if files[n] is not None]
    if not present:
        emit("**No result file exists.** The benchmark produced no data, so "
             "there is nothing to audit and nothing to report. This is a "
             "complete result in itself: absent, not empty, not estimated.")
    if FAILURES:
        emit("\n**%d FAILURE(S)**" % len(FAILURES))
        for f in FAILURES:
            emit("  - %s" % f)
    if WARNINGS:
        emit("\n%d warning(s)" % len(WARNINGS))
        for w in WARNINGS:
            emit("  - %s" % w)
    if not FAILURES and present:
        emit("\nAll checks passed on the files that exist.")

    out.write_text("\n".join(REPORT) + "\n", encoding="utf-8")
    print("\nWrote %s" % out)
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
